package structure

import (
	"slices"
	"strings"
	"testing"
	"testing/fstest"
)

// imports is a file in package p that imports the module's package dir.
func imports(p, dir string) string {
	return "package " + p + "\n\nimport _ \"example.com/m/" + dir + "\"\n"
}

// A ruleCase is a module's files and the one violation check finds in it.
type ruleCase struct {
	name  string
	files map[string]string
	r     rules // maxMethods 2 and devvm's layers unless set
	want  *want // nil: no violation
}

type want struct{ rule, text string }

// methodCases break and keep max-methods and no-init.
func methodCases() []ruleCase {
	return []ruleCase{
		{
			name:  "methods over the limit",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) A() {}\nfunc (*T) B() {}\nfunc (T) C() {}\n"},
			want:  &want{ruleMethods, "type T has 3 methods"},
		},
		{
			name: "methods across files",
			files: map[string]string{
				"a/a.go": "package a\ntype T[K any] int\nfunc (T[K]) A() {}\nfunc (*T[K]) B() {}\n",
				"a/b.go": "package a\nfunc (T[K]) C() {}\n",
			},
			want: &want{ruleMethods, "type T has 3 methods"},
		},
		{
			name:  "methods at the limit",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) A() {}\nfunc (*T) B() {}\n"},
		},
		{
			name: "methods in a generated file",
			files: map[string]string{"a/a.go": "// Code generated by x. DO NOT EDIT.\n\npackage a\ntype T int\n" +
				"func (T) A() {}\nfunc (T) B() {}\nfunc (T) C() {}\n"},
		},
		{
			name:  "a large type within its max",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) A() {}\nfunc (T) B() {}\nfunc (T) C() {}\n"},
			r:     rules{largeTypes: map[string]large{"a.T": {3, "x"}}},
		},
		{
			name:  "a large type grown",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) A() {}\nfunc (T) B() {}\nfunc (T) C() {}\nfunc (T) D() {}\n"},
			r:     rules{largeTypes: map[string]large{"a.T": {3, "x"}}},
			want:  &want{ruleMethods, "more than its 3 in largeTypes"},
		},
		{
			name:  "a large type shrunk",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) A() {}\nfunc (T) B() {}\nfunc (T) C() {}\n"},
			r:     rules{largeTypes: map[string]large{"a.T": {4, "x"}}},
			want:  &want{ruleMethods, "lower its max"},
		},
		{
			name:  "a large type no longer large",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) A() {}\n"},
			r:     rules{largeTypes: map[string]large{"a.T": {3, "x"}}},
			want:  &want{ruleMethods, "take it out of largeTypes"},
		},
		{
			name:  "a large type gone",
			files: map[string]string{"a/a.go": "package a\n"},
			r:     rules{largeTypes: map[string]large{"a.T": {3, "x"}}},
			want:  &want{ruleMethods, "a.T has no methods"},
		},
		{
			name:  "init",
			files: map[string]string{"a/a.go": "package a\nfunc init() {}\n"},
			want:  &want{ruleInit, "func init"},
		},
		{
			name:  "init in a test",
			files: map[string]string{"a/a_test.go": "package a_test\nfunc init() {}\n"},
			want:  &want{ruleInit, "func init"},
		},
		{
			name:  "an init method",
			files: map[string]string{"a/a.go": "package a\ntype T int\nfunc (T) init() {}\n"},
		},
	}
}

// varCases break and keep package-vars.
func varCases() []ruleCase {
	return []ruleCase{
		{
			name:  "a var",
			files: map[string]string{"a/a.go": "package a\nvar Hook = func() {}\n"},
			want:  &want{ruleVars, "var Hook"},
		},
		{
			name:  "a var in a test",
			files: map[string]string{"a/a_test.go": "package a\nvar calls []string\n"},
			want:  &want{ruleVars, "var calls"},
		},
		{
			name:  "a var in a group",
			files: map[string]string{"a/a.go": "package a\nvar (\n\tre = regexp.MustCompile(`x`)\n\tn  = 1\n)\n"},
			want:  &want{ruleVars, "var n"},
		},
		{
			name:  "an error not named as a sentinel",
			files: map[string]string{"a/a.go": "package a\nvar missing = errors.New(\"x\")\n"},
			want:  &want{ruleVars, "var missing"},
		},
		{
			name: "constants' kin",
			files: map[string]string{
				"a/a.go": "package a\n" +
					"var ErrX = errors.New(\"x\")\nvar errY = fmt.Errorf(\"y\")\n" +
					"var re = regexp.MustCompile(`x`)\nvar tmpl = template.Must(template.New(\"t\").Parse(\"\"))\n" +
					"var home = sync.OnceValue[string](func() string { return \"\" })\nvar f = sync.OnceFunc(func() {})\n" +
					"//go:embed x\nvar files embed.FS\n" +
					"var _ error = (*T)(nil)\n",
			},
		},
		{
			name:  "internal/proxy's state",
			files: map[string]string{"internal/proxy/a.go": "package proxy\nvar port int\n"},
		},
		{
			name:  "an allowed var",
			files: map[string]string{"a/a.go": "package a\nvar version = \"dev\"\n"},
			r:     rules{allowedVars: map[string]string{"a.version": "x"}},
		},
		{
			name:  "an allowed var gone",
			files: map[string]string{"a/a.go": "package a\n"},
			r:     rules{allowedVars: map[string]string{"a.version": "x"}},
			want:  &want{ruleVars, "a.version is no package-level var"},
		},
	}
}

// layerCases break each of devvm's layers, and keep some.
func layerCases() []ruleCase {
	return []ruleCase{
		{
			name:  "ui outside cli",
			files: map[string]string{"internal/build/a.go": imports("build", "internal/ui")},
			want:  &want{ruleLayers, "hold the UI"},
		},
		{
			name:  "ui in cli",
			files: map[string]string{"internal/cli/docgen/a.go": imports("main", "internal/ui")},
		},
		{
			name:  "vm outside cli",
			files: map[string]string{"internal/tools/a.go": imports("tools", "internal/vm")},
			want:  &want{ruleLayers, "commands on VMs"},
		},
		{
			name:  "cli outside main",
			files: map[string]string{"internal/vm/a.go": imports("vm", "internal/cli")},
			want:  &want{ruleLayers, "only cmd/devvm runs the commands"},
		},
		{
			name:  "a backend above its users",
			files: map[string]string{"internal/backend/lima/a.go": imports("lima", "internal/build")},
			want:  &want{ruleLayers, "backends are below"},
		},
		{
			name:  "a backend named outside the registry",
			files: map[string]string{"internal/vm/a.go": imports("vm", "internal/backend/smolvm")},
			want:  &want{ruleLayers, "name a backend"},
		},
		{
			name:  "a backend named in a test",
			files: map[string]string{"internal/netpolicy/a_test.go": imports("netpolicy", "internal/backend/lima")},
		},
		{
			name:  "backendtest outside tests",
			files: map[string]string{"internal/build/a.go": imports("build", "internal/backend/backendtest")},
			want:  &want{ruleLayers, "backendtest is for tests"},
		},
		{
			name:  "proxy importing devvm",
			files: map[string]string{"internal/proxy/a.go": imports("proxy", "internal/msg")},
			want:  &want{ruleLayers, "standard library only"},
		},
		{
			name:  "a leaf importing devvm",
			files: map[string]string{"internal/platform/a.go": imports("platform", "internal/msg")},
			want:  &want{ruleLayers, "leaves import nothing"},
		},
		{
			name:  "msg importing more",
			files: map[string]string{"internal/msg/a.go": imports("msg", "internal/paths")},
			want:  &want{ruleLayers, "internal/msg imports only"},
		},
		{
			name:  "paths importing more",
			files: map[string]string{"internal/paths/a.go": imports("paths", "internal/state")},
			want:  &want{ruleLayers, "internal/paths imports only"},
		},
		{
			name:  "state importing more",
			files: map[string]string{"internal/state/a.go": imports("state", "internal/image")},
			want:  &want{ruleLayers, "internal/state imports only"},
		},
		{
			name:  "image importing more",
			files: map[string]string{"internal/image/a.go": imports("image", "internal/state")},
			want:  &want{ruleLayers, "internal/image imports only"},
		},
		{
			name:  "devcontainer importing more",
			files: map[string]string{"internal/devcontainer/a.go": imports("devcontainer", "internal/from")},
			want:  &want{ruleLayers, "internal/devcontainer imports only"},
		},
	}
}

// Each rule fails on code that breaks it, naming the rule, and passes
// what it allows.
func TestRulesFail(t *testing.T) {
	var broken []string // the layer violations' texts
	for _, tc := range slices.Concat(methodCases(), varCases(), layerCases()) {
		t.Run(tc.name, func(t *testing.T) {
			fsys := fstest.MapFS{"go.mod": {Data: []byte("module example.com/m\n\ngo 1.27\n")}}
			for name, src := range tc.files {
				fsys[name] = &fstest.MapFile{Data: []byte(src)}
			}
			m, err := load(fsys)
			if err != nil {
				t.Fatal(err)
			}
			r := tc.r
			if r.maxMethods == 0 {
				r.maxMethods = 2
			}
			if r.layers == nil {
				r.layers = devvm().layers
			}
			vs := check(m, r)
			if tc.want == nil {
				if len(vs) != 0 {
					t.Errorf("got %q, want none", vs)
				}
				return
			}
			if len(vs) != 1 || vs[0].rule != tc.want.rule || !strings.Contains(vs[0].text, tc.want.text) {
				t.Errorf("got %q, want one %s violation saying %q", vs, tc.want.rule, tc.want.text)
			}
			if len(vs) == 1 && vs[0].rule == ruleLayers {
				broken = append(broken, vs[0].text)
			}
		})
	}
	// Every layer has a case that breaks it.
	for _, l := range devvm().layers {
		if !slices.ContainsFunc(broken, func(text string) bool { return strings.HasSuffix(text, ": "+l.name) }) {
			t.Errorf("no case breaks layer %q", l.name)
		}
	}
}
